let current = 'ko';

export function setLanguage(lang) {
  current = resolveLanguage(lang);
}

export function resolveLanguage(lang) {
  if (lang === 'auto') {
    try {
      const languages = navigator.languages || [navigator.language || 'ko'];
      return languages.some(value => value.toLowerCase().startsWith('ko')) ? 'ko' : 'en';
    } catch {
      return 'ko';
    }
  }
  return lang === 'en' ? 'en' : 'ko';
}

export function t(key, params) {
  let text = STRINGS[current][key] ?? STRINGS.ko[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(`{${k}}`, String(v));
    }
  }
  return text;
}

export function applyDomStrings(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-aria]').forEach(el => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
  root.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.setAttribute('title', t(el.dataset.i18nTitle));
  });
  if (root === document && document.documentElement) {
    document.documentElement.lang = current;
  }
}

